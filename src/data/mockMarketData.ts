/**
 * Generates deterministic realistic candlestick data based on symbol, price, and timeframe
 */
export function generateCandles(symbol: string, currentPrice: number, timeframe: Timeframe): CandleData[] {
  let count = 40;
  let intervalMinutes = 5;
  let volatility = 0.008;

  switch (timeframe) {
    case '1D':
      count = 50;
      intervalMinutes = 5;
      volatility = 0.004;
      break;
    case '5D':
      count = 45;
      intervalMinutes = 30;
      volatility = 0.008;
      break;
    case '1M':
      count = 35;
      intervalMinutes = 60 * 24;
      volatility = 0.015;
      break;
    case '3M':
      count = 45;
      intervalMinutes = 60 * 24 * 2;
      volatility = 0.022;
      break;
    case '6M':
      count = 50;
      intervalMinutes = 60 * 24 * 3;
      volatility = 0.028;
      break;
    case '1Y':
      count = 52;
      intervalMinutes = 60 * 24 * 7;
      volatility = 0.035;
      break;
    case '5Y':
      count = 60;
      intervalMinutes = 60 * 24 * 30;
      volatility = 0.055;
      break;
    case 'ALL':
      count = 65;
      intervalMinutes = 60 * 24 * 45;
      volatility = 0.07;
      break;
  }

  // Use symbol hash for deterministic pattern
  let seed = 0;
  for (let i = 0; i < symbol.length; i++) {
    seed = (seed << 5) - seed + symbol.charCodeAt(i);
    seed |= 0;
  }
  const random = () => {
    seed = (seed * 9301 + 49297) % 233280;
    return seed / 233280;
  };

  const candles: CandleData[] = [];
  const now = Date.now();
  let basePrice = currentPrice * (1 - (count * 0.003));

  for (let i = 0; i < count; i++) {
    const timestamp = now - (count - i) * intervalMinutes * 60 * 1000;
    const dateObj = new Date(timestamp);
    const timeLabel =
      timeframe === '1D'
        ? dateObj.toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' })
        : dateObj.toLocaleDateString([], { month: 'short', day: 'numeric' });

    // Calculate realistic walk
    const trend = (currentPrice - basePrice) / (count - i || 1);
    const step = (random() - 0.48) * currentPrice * volatility + trend * 0.4;
    const open = i === 0 ? basePrice : candles[i - 1].close;
    const close = Math.max(1, i === count - 1 ? currentPrice : open + step);
    const spread = Math.abs(close - open);
    const high = Math.max(open, close) + random() * spread * 0.8 + currentPrice * (volatility * 0.2);
    const low = Math.min(open, close) - random() * spread * 0.8 - currentPrice * (volatility * 0.2);
    const volume = Math.floor(100000 + random() * 2500000 * (1 + spread / (currentPrice * 0.01)));

    candles.push({
      time: timeLabel,
      timestamp,
      open: Number(open.toFixed(2)),
      high: Number(high.toFixed(2)),
      low: Number(low.toFixed(2)),
      close: Number(close.toFixed(2)),
      volume,
    });
  }

  return candles;
}
